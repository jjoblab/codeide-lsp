package jo.lspjava.ecj;

import org.eclipse.jdt.internal.compiler.classfmt.ClassFileConstants;
import org.eclipse.jdt.internal.compiler.classfmt.ClassFileReader;
import org.eclipse.jdt.internal.compiler.env.IBinaryField;
import org.eclipse.jdt.internal.compiler.env.IBinaryMethod;

/**
 * Génère un squelette Java synthétique à partir d'un
 * {@link ClassFileReader} binaire, pour la fonctionnalité « GO TO
 * Definition sur cible binaire ».
 *
 * <p>Le squelette n'est PAS une recompilation fidèle (CFR/Procyon
 * seraient surdimensionnés pour ce besoin) — c'est un squelette de
 * navigation qui préserve les signatures publiques, protégées et
 * par défaut de la classe : déclaration {@code package}, déclaration
 * de classe avec superclasse + interfaces, champs (modificateurs +
 * type + nom), méthodes (modificateurs + type de retour + nom +
 * paramètres typés {@code p0, p1, ...} + clause {@code throws} +
 * corps {@code throw new RuntimeException("decompiled stub");}).
 *
 * <p>Le but est de donner à l'utilisateur un « atterrissage »
 * navigable quand il Go-To sur une classe du JDK ou d'une lib externe
 * sans source attachée — il voit au moins les signatures publiques
 * et peut naviguer dans la liste des méthodes.
 */
final class ClassFileStubBuilder {

    private ClassFileStubBuilder() {}

    /**
     * Construit le squelette décompilé.
     *
     * @param fqcn   fully-qualified name (ex. {@code java.util.HashMap})
     * @param reader le {@link ClassFileReader} du type binaire
     * @return le texte source du stub, jamais null
     */
    static String build(String fqcn, ClassFileReader reader) {
        StringBuilder sb = new StringBuilder(2048);
        int lastDot = fqcn.lastIndexOf('.');
        String pkg = lastDot > 0 ? fqcn.substring(0, lastDot) : "";
        String simpleName = lastDot > 0 ? fqcn.substring(lastDot + 1) : fqcn;

        // En-tête.
        sb.append("// Decompiled from ").append(fqcn).append(".class\n");
        sb.append("// Generated by CodeIDE v2.39 — navigation stub (no bodies).\n\n");
        if (!pkg.isEmpty()) {
            sb.append("package ").append(pkg).append(";\n\n");
        }

        // Modificateurs de classe.
        int classMods = reader.getModifiers();
        boolean isInterface = (classMods & ClassFileConstants.AccInterface) != 0;
        boolean isAnnotation = (classMods & ClassFileConstants.AccAnnotation) != 0;
        boolean isEnum = (classMods & ClassFileConstants.AccEnum) != 0;

        // Déclaration de classe.
        sb.append(modifierString(classMods, isInterface));
        if (isAnnotation) sb.append("@interface ");
        else if (isInterface) sb.append("interface ");
        else if (isEnum) sb.append("enum ");
        else sb.append("class ");
        sb.append(simpleName);

        // Superclasse (sauf pour java.lang.Object et interfaces pures).
        char[] superclassName = reader.getSuperclassName();
        if (superclassName != null) {
            String superFqn = new String(superclassName).replace('/', '.');
            if (!superFqn.equals("java.lang.Object") && !isInterface) {
                sb.append(" extends ").append(superFqn);
            }
        }
        // Interfaces.
        char[][] interfaces = reader.getInterfaceNames();
        if (interfaces != null && interfaces.length > 0) {
            sb.append(isInterface ? " extends " : " implements ");
            for (int i = 0; i < interfaces.length; i++) {
                if (i > 0) sb.append(", ");
                sb.append(new String(interfaces[i]).replace('/', '.'));
            }
        }
        sb.append(" {\n\n");

        // Champs.
        IBinaryField[] fields = reader.getFields();
        if (fields != null && fields.length > 0) {
            sb.append("    // ── Fields ───────────────────────────────────────\n");
            for (IBinaryField f : fields) {
                if (f == null) continue;
                // Saute les champs synthétiques.
                if ((f.getModifiers() & ClassFileConstants.AccSynthetic) != 0) continue;
                sb.append("    ");
                sb.append(modifierString(f.getModifiers(), false));
                // Préfère la signature générique si disponible ; sinon le nom de type.
                char[] sig = f.getGenericSignature();
                char[] typeName = f.getTypeName();
                String typeSig = sig != null && sig.length > 0
                    ? new String(sig) : (typeName != null ? new String(typeName) : "Object");
                sb.append(typeSignatureToJava(typeSig))
                  .append(' ')
                  .append(new String(f.getName()))
                  .append(";\n");
            }
            sb.append('\n');
        }

        // Méthodes.
        IBinaryMethod[] methods = reader.getMethods();
        if (methods != null && methods.length > 0) {
            sb.append("    // ── Methods ──────────────────────────────────────\n");
            for (IBinaryMethod m : methods) {
                if (m == null) continue;
                if (m.isClinit()) continue;
                // Saute les méthodes bridge synthétiques.
                if ((m.getModifiers() & ClassFileConstants.AccSynthetic) != 0) continue;
                if ((m.getModifiers() & ClassFileConstants.AccBridge) != 0) continue;

                char[] selector = m.getSelector();
                if (selector == null) continue;
                String name = new String(selector);

                sb.append("    ");
                int mmods = m.getModifiers();
                boolean isNative = (mmods & ClassFileConstants.AccNative) != 0;
                boolean isMethodAbstract = (mmods & ClassFileConstants.AccAbstract) != 0;
                // Pour les méthodes d'interface, abstract est implicite sauf
                // pour les default methods.
                boolean isInterfaceMethod = isInterface;
                boolean isDefaultMethod = isInterface
                    && (mmods & ClassFileConstants.AccAbstract) == 0;

                sb.append(modifierString(mmods, isInterfaceMethod && !isDefaultMethod));
                // Utiliser la signature GÉNÉRIQUE si disponible
                // (getGenericSignature) au lieu du descripteur brut
                // (getMethodDescriptor) : le descripteur rendrait `List foo()`
                // au lieu de `List<String> foo()`. Quand getGenericSignature
                // retourne non-null, on parse la signature générique qui
                // inclut les paramètres de type.
                char[] genSig = m.getGenericSignature();
                String descriptor;
                String[] params;
                String returnType;
                String typeParamsPrefix = "";
                if (genSig != null && genSig.length > 0) {
                    String sig = new String(genSig);
                    // La signature générique peut commencer par <T:Bound;>...
                    // On extrait les paramètres de type pour les afficher.
                    if (sig.startsWith("<")) {
                        int gt = sig.indexOf('>');
                        if (gt > 0) {
                            String typeParams = sig.substring(1, gt);
                            typeParamsPrefix = parseTypeParameters(typeParams);
                            sig = sig.substring(gt + 1);
                        }
                    }
                    // Ici sig est "(params)ReturnType" avec génériques.
                    params = parseMethodParamsGeneric(sig);
                    returnType = parseMethodReturnTypeGeneric(sig);
                } else {
                    descriptor = m.getMethodDescriptor() != null
                        ? new String(m.getMethodDescriptor()) : "()V";
                    params = parseMethodParams(descriptor);
                    returnType = parseMethodReturnType(descriptor);
                }
                // Constructeur : le nom de la classe sert de nom de méthode ;
                // pas de type de retour.
                if (name.equals("<init>")) {
                    sb.append(simpleName);
                } else {
                    // Afficher les paramètres de type si présents.
                    if (!typeParamsPrefix.isEmpty()) {
                        sb.append(typeParamsPrefix).append(' ');
                    }
                    sb.append(returnType).append(' ').append(name);
                }
                // Paramètres.
                sb.append('(');
                for (int i = 0; i < params.length; i++) {
                    if (i > 0) sb.append(", ");
                    sb.append(params[i]).append(" p").append(i);
                }
                sb.append(')');
                // Clause throws.
                char[][] throwsExceptions = m.getExceptionTypeNames();
                if (throwsExceptions != null && throwsExceptions.length > 0) {
                    sb.append(" throws ");
                    for (int i = 0; i < throwsExceptions.length; i++) {
                        if (i > 0) sb.append(", ");
                        sb.append(new String(throwsExceptions[i]).replace('/', '.'));
                    }
                }
                // Corps.
                if (isNative) {
                    sb.append(";  // native\n");
                } else if (isMethodAbstract
                        || (isInterfaceMethod && !isDefaultMethod)) {
                    sb.append(";\n");
                } else {
                    sb.append(" {\n");
                    sb.append("        throw new RuntimeException(\"Decompiled stub — ");
                    sb.append(simpleName).append('.').append(name).append("\");\n");
                    sb.append("    }\n");
                }
            }
        }

        sb.append("}\n");
        return sb.toString();
    }

    /**
     * Convertit les modificateurs JVM en chaîne Java (ex. {@code "public static final "}).
     * Pour les interfaces, on n'émet pas {@code abstract} (implicite).
     */
    private static String modifierString(int mods, boolean isAbstractImplicit) {
        StringBuilder sb = new StringBuilder();
        if ((mods & ClassFileConstants.AccPublic) != 0) sb.append("public ");
        if ((mods & ClassFileConstants.AccProtected) != 0) sb.append("protected ");
        if ((mods & ClassFileConstants.AccPrivate) != 0) sb.append("private ");
        // Pour les interfaces, abstract est implicite.
        if ((mods & ClassFileConstants.AccAbstract) != 0 && !isAbstractImplicit) {
            sb.append("abstract ");
        }
        if ((mods & ClassFileConstants.AccStatic) != 0) sb.append("static ");
        if ((mods & ClassFileConstants.AccFinal) != 0) sb.append("final ");
        if ((mods & ClassFileConstants.AccSynchronized) != 0) sb.append("synchronized ");
        if ((mods & ClassFileConstants.AccTransient) != 0) sb.append("transient ");
        if ((mods & ClassFileConstants.AccVolatile) != 0) sb.append("volatile ");
        if ((mods & ClassFileConstants.AccNative) != 0) sb.append("native ");
        return sb.toString();
    }

    /**
     * Convertit une signature de type JVM (ex. {@code Ljava/lang/String;},
     * {@code I}, {@code [I}, {@code V}) en sa représentation Java lisible.
     */
    private static String typeSignatureToJava(String sig) {
        if (sig == null || sig.isEmpty()) return "void";
        int[] pos = {0};
        String parsed = parseType(sig, pos);
        return parsed != null ? parsed : "Object";
    }

    /**
     * Parse la liste des types de paramètres depuis un descripteur JVM
     * de la forme {@code (Larg1;Larg2;I)V}.
     */
    private static String[] parseMethodParams(String descriptor) {
        if (descriptor == null || descriptor.isEmpty()
                || descriptor.charAt(0) != '(') return new String[0];
        int[] pos = {1};  // saute '('
        java.util.List<String> params = new java.util.ArrayList<>();
        while (pos[0] < descriptor.length() && descriptor.charAt(pos[0]) != ')') {
            String t = parseType(descriptor, pos);
            if (t == null) break;
            params.add(t);
        }
        return params.toArray(new String[0]);
    }

    /**
     * Extrait le type de retour depuis un descripteur JVM
     * (la partie après le ')').
     */
    private static String parseMethodReturnType(String descriptor) {
        if (descriptor == null || descriptor.isEmpty()) return "void";
        int closeIdx = descriptor.indexOf(')');
        if (closeIdx < 0 || closeIdx + 1 >= descriptor.length()) return "void";
        int[] pos = {closeIdx + 1};
        String t = parseType(descriptor, pos);
        return t != null ? t : "void";
    }

    /**
     * Parse récursivement un type JVM à partir de {@code sig[pos[0]]}.
     * Avance {@code pos} au-delà du type consommé.
     *
     * <p>Supporte les primitives ({@code I}, {@code J}, {@code Z}, etc.),
     * les tableaux ({@code [T}), les objets ({@code Lfqcn;}). Les
     * génériques (signature étendue) ne sont pas gérés ici — on
     * consomme juste le type "raw".
     */
    private static String parseType(String sig, int[] pos) {
        if (pos[0] >= sig.length()) return null;
        char c = sig.charAt(pos[0]);
        switch (c) {
            case 'V': pos[0]++; return "void";
            case 'B': pos[0]++; return "byte";
            case 'C': pos[0]++; return "char";
            case 'D': pos[0]++; return "double";
            case 'F': pos[0]++; return "float";
            case 'I': pos[0]++; return "int";
            case 'J': pos[0]++; return "long";
            case 'S': pos[0]++; return "short";
            case 'Z': pos[0]++; return "boolean";
            case '[': pos[0]++; return parseType(sig, pos) + "[]";
            case 'L': {
                pos[0]++;
                int end = sig.indexOf(';', pos[0]);
                if (end < 0) return null;
                String raw = sig.substring(pos[0], end).replace('/', '.');
                // Retire les paramètres de type éventuels (la signature
                // générique utilise '<...>').
                int lt = raw.indexOf('<');
                if (lt >= 0) raw = raw.substring(0, lt);
                pos[0] = end + 1;
                // Aplatit les classes internes '$' → '.' pour la lisibilité.
                return raw.replace('$', '.');
            }
            case 'T': {
                // Variable de type — rendue comme Object (avec perte mais navigable).
                int semi = sig.indexOf(';', pos[0]);
                pos[0] = semi + 1;
                return "Object";
            }
            case '+':
            case '-':
                // Wildcard — consommée puis récursion.
                pos[0]++;
                return "? extends " + parseType(sig, pos);
            case '*':
                pos[0]++;
                return "?";
            default:
                return null;
        }
    }

    // ── Parsing des signatures génériques de méthode ──────

    /**
     * Parse les paramètres de type d'une signature générique de méthode.
     * Format JVM : {@code T:Ljava/lang/Object;U:Ljava/lang/Number;:Ljava/lang/Comparable<TU;>;}
     * → {@code <T, U extends Number & Comparable<U>>}
     */
    private static String parseTypeParameters(String sig) {
        StringBuilder sb = new StringBuilder("<");
        int[] pos = {0};
        boolean first = true;
        while (pos[0] < sig.length()) {
            // Nom du paramètre de type
            int colon = sig.indexOf(':', pos[0]);
            if (colon < 0) break;
            String name = sig.substring(pos[0], colon);
            if (!first) sb.append(", ");
            sb.append(name);
            pos[0] = colon + 1;
            // Bounds : premier bound (classe), bounds suivants (interfaces)
            boolean firstBound = true;
            while (pos[0] < sig.length() && sig.charAt(pos[0]) == ':') {
                pos[0]++; // skip ':'
                String bound = parseType(sig, pos);
                if (bound != null && !bound.equals("java.lang.Object")) {
                    if (firstBound) {
                        sb.append(" extends ").append(bound);
                    } else {
                        sb.append(" & ").append(bound);
                    }
                }
                firstBound = false;
            }
            first = false;
        }
        sb.append('>');
        return sb.toString();
    }

    /**
     * Parse les paramètres d'une signature générique de méthode.
     * Format : {@code (Lfoo/Bar<Ljava/lang/String;>;I)V}
     */
    private static String[] parseMethodParamsGeneric(String sig) {
        if (sig == null || !sig.startsWith("(")) return new String[0];
        int close = sig.indexOf(')');
        if (close < 0) return new String[0];
        String params = sig.substring(1, close);
        java.util.List<String> out = new java.util.ArrayList<>();
        int[] pos = {0};
        while (pos[0] < params.length()) {
            String t = parseType(params, pos);
            if (t == null) break;
            out.add(t);
        }
        return out.toArray(new String[0]);
    }

    /**
     * Parse le type de retour d'une signature générique de méthode.
     */
    private static String parseMethodReturnTypeGeneric(String sig) {
        if (sig == null) return "void";
        int close = sig.indexOf(')');
        if (close < 0) return "void";
        String ret = sig.substring(close + 1);
        int[] pos = {0};
        String t = parseType(ret, pos);
        return t != null ? t : "void";
    }
}
